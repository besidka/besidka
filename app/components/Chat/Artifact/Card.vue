<template>
  <section
    v-if="model"
    class="mt-2 w-full max-w-sm"
    aria-live="polite"
  >
    <div
      v-if="model.state === 'failed'"
      class="alert alert-error alert-soft items-start"
      role="alert"
      data-testid="artifact-card-failed"
    >
      <Icon
        name="lucide:circle-alert"
        size="18"
        class="shrink-0"
      />
      <div class="min-w-0">
        <p
          class="font-medium"
          data-testid="artifact-card-failed-title"
        >
          {{ model.errorTitle || failedTitle }}
        </p>
        <p
          v-if="model.errorText"
          class="text-sm break-words"
          data-testid="artifact-card-failed-reason"
        >
          {{ model.errorText }}
        </p>
      </div>
    </div>
    <p
      v-else-if="isUnavailable"
      class="flex items-center gap-2 rounded-box border border-base-300 px-3 py-2 text-sm text-base-content/60"
      data-testid="artifact-card-unavailable"
    >
      <Icon
        name="lucide:file-x"
        size="16"
        class="shrink-0"
      />
      Artifact unavailable
    </p>
    <button
      v-else
      type="button"
      class="flex w-full items-center gap-3 rounded-box border border-base-300 bg-base-200 p-3 text-left cursor-pointer transition-colors duration-150 hover:bg-base-300/60 disabled:cursor-default focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-accent"
      :class="{ 'border-accent': isActive }"
      :aria-label="`Open ${displayTitle}`"
      :aria-current="isActive ? 'true' : undefined"
      :disabled="!canOpen"
      :data-state="model.state"
      data-testid="artifact-card"
      @click="onOpen"
    >
      <span class="grid size-10 shrink-0 place-items-center rounded-field bg-base-100 text-base-content/70">
        <Icon
          :name="iconName"
          size="20"
        />
      </span>
      <span class="min-w-0 grow">
        <span
          class="block truncate text-sm font-medium"
          data-testid="artifact-card-title"
        >
          {{ displayTitle }}
        </span>
        <span class="mt-1 flex flex-wrap items-center gap-1">
          <span
            v-if="model.kind"
            class="badge badge-soft badge-sm"
            data-testid="artifact-card-kind"
          >
            {{ ARTIFACT_KIND_LABELS[model.kind] }}
          </span>
          <span
            v-if="model.state === 'ready' && model.version !== null"
            class="text-xs text-base-content/60"
            data-testid="artifact-card-version"
          >
            v{{ model.version }}
          </span>
          <span
            v-if="model.state === 'streaming' && lineCount > 0"
            class="text-xs text-base-content/60"
            data-testid="artifact-card-lines"
          >
            {{ lineCountLabel }}
          </span>
          <span
            class="badge badge-ghost badge-sm"
            title="Content generated by AI"
          >
            AI-generated
          </span>
        </span>
        <span
          v-if="model.state === 'streaming'"
          class="skeleton skeleton--default mt-2 block h-1.5 w-full"
          data-testid="artifact-card-progress"
        />
      </span>
      <span
        v-if="model.state === 'ready'"
        class="btn btn-sm shrink-0"
        aria-hidden="true"
      >
        Open
      </span>
    </button>
  </section>
</template>

<script setup lang="ts">
import type {
  ArtifactPanelSource,
  ArtifactPanelTarget,
} from '~/composables/artifacts'
import { getArtifactViewKey } from '~/composables/artifacts'
import {
  ARTIFACT_KIND_ICONS,
  ARTIFACT_KIND_LABELS,
  countArtifactLines,
  getArtifactPartModel,
} from '~/utils/artifact-parts'

const props = defineProps<{
  part: unknown
  source: ArtifactPanelSource
  shareSlug?: string
  chatId?: string | null
}>()

const panel = useArtifactPanel()
const { tryAutoOpen } = useArtifactAutoOpen()

const model = computed(() => {
  return getArtifactPartModel(props.part)
})

const displayTitle = computed<string>(() => {
  const current = model.value

  if (current?.title) {
    return current.title
  }

  if (current?.state === 'streaming') {
    return current.operation === 'update'
      ? 'Updating artifact…'
      : 'Writing artifact…'
  }

  return 'Untitled artifact'
})

const failedTitle = computed<string>(() => {
  const title = model.value?.title

  return title ? `Couldn't save "${title}"` : 'Couldn\'t save the artifact'
})

const iconName = computed<string>(() => {
  const kind = model.value?.kind

  return kind ? ARTIFACT_KIND_ICONS[kind] : 'lucide:app-window'
})

const lineCount = computed<number>(() => {
  return countArtifactLines(model.value?.content ?? '')
})

const lineCountLabel = computed<string>(() => {
  return lineCount.value === 1 ? '1 line' : `${lineCount.value} lines`
})

const target = computed<ArtifactPanelTarget | null>(() => {
  const current = model.value

  if (!current || current.state === 'failed') {
    return null
  }

  return {
    artifactId: current.artifactId,
    version: current.version,
    kind: current.kind,
    title: current.title || displayTitle.value,
    source: props.source,
    shareSlug: props.shareSlug,
    toolCallId: current.toolCallId ?? undefined,
  }
})

const viewKey = computed<string | null>(() => {
  const current = model.value

  if (!current) {
    return null
  }

  return getArtifactViewKey({
    artifactId: current.artifactId,
    toolCallId: current.toolCallId ?? undefined,
  })
})

const isViewOpen = computed<boolean>(() => {
  return !!viewKey.value && panel.isOpenOn(viewKey.value)
})

const isActive = computed<boolean>(() => {
  const version = model.value?.version ?? null
  const openVersion = panel.state.value?.version ?? null

  return isViewOpen.value
    && (version === null || openVersion === null || openVersion === version)
})

const isUnavailable = computed<boolean>(() => {
  const artifactId = model.value?.artifactId

  return model.value?.state === 'ready'
    && !!artifactId
    && panel.isUnavailable(artifactId)
})

const canOpen = computed<boolean>(() => {
  const current = model.value

  if (!current || !target.value) {
    return false
  }

  if (current.state === 'ready') {
    return !!current.artifactId
  }

  return current.operation === 'create' || !!current.artifactId
})

let hasTriedAutoOpen = false

watch(model, (current) => {
  if (
    hasTriedAutoOpen
    || !current
    || current.state !== 'streaming'
    || current.operation !== 'create'
    || props.source !== 'owner'
    || !props.chatId
    || !target.value
  ) {
    return
  }

  hasTriedAutoOpen = true
  tryAutoOpen(props.chatId, target.value)
}, { immediate: true })

watch([model, isActive], ([current, active]) => {
  if (!active || !current?.toolCallId || !viewKey.value) {
    return
  }

  if (current.state === 'streaming') {
    if (current.operation === 'create') {
      panel.setStream({
        toolCallId: current.toolCallId,
        kind: current.kind,
        title: current.title,
        content: current.content,
        status: 'streaming',
      })
    }

    if (current.title) {
      panel.updateTarget(viewKey.value, {
        title: current.title,
        kind: current.kind ?? panel.state.value?.kind ?? null,
      })
    }

    return
  }

  if (current.state === 'ready') {
    panel.updateTarget(viewKey.value, {
      artifactId: current.artifactId,
      version: current.version,
      kind: current.kind,
      title: current.title,
    })
  }

  const finalStatus = current.state === 'ready' ? 'done' : 'failed'

  if (
    panel.stream.value?.toolCallId === current.toolCallId
    && panel.stream.value.status !== finalStatus
  ) {
    panel.setStream({
      ...panel.stream.value,
      status: finalStatus,
      ...(finalStatus === 'failed'
        ? {
          errorText: [current.errorTitle, current.errorText]
            .filter(Boolean)
            .join(' '),
        }
        : {}),
    })
  }
}, { immediate: true })

function onOpen() {
  if (!target.value || !canOpen.value || isActive.value) {
    return
  }

  if (isViewOpen.value && target.value.version !== null) {
    panel.selectVersion(target.value.version)

    return
  }

  panel.open(target.value)
}
</script>
