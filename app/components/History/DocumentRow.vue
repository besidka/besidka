<template>
  <li
    class="
      list-row items-center gap-3 group py-3 sm:py-2 relative
      [&:has(details[open])]:z-30
    "
    data-testid="document-row"
    :data-document-id="item.id"
  >
    <span
      class="grid size-10 shrink-0 place-items-center rounded-field bg-base-200 text-base-content/70"
      aria-hidden="true"
    >
      <Icon
        :name="DOCUMENT_FORMAT_ICONS[item.format]"
        size="20"
      />
    </span>

    <div class="list-col-grow flex-1 min-w-0">
      <button
        type="button"
        class="link no-underline rounded-box block w-full truncate py-1 text-left font-medium"
        :title="item.fileName"
        data-testid="document-row-open"
        @click="onPreview"
      >
        {{ item.title }}
      </button>
      <div class="mt-0.5 flex flex-wrap items-center gap-x-2 gap-y-1 text-xs text-base-content/70">
        <span
          class="badge badge-soft badge-sm"
          data-testid="document-row-format"
        >
          {{ DOCUMENT_FORMAT_LIBRARY_LABELS[item.format] }}
        </span>
        <span
          class="badge badge-soft badge-sm gap-1"
          data-testid="document-row-source"
        >
          <Icon
            :name="sourceIcon"
            size="10"
            aria-hidden="true"
          />
          <NuxtLink
            v-if="hasOriginChat"
            :to="`/chats/${item.originChatSlug}`"
            class="link link-hover max-w-40 truncate"
            :title="item.originChatTitle || UNTITLED_CHAT_LABEL"
            data-testid="document-row-source-link"
          >
            {{ sourceLabel }}
          </NuxtLink>
          <span
            v-else
            :title="isConnectedApp ? undefined : DELETED_CHAT_LABEL"
          >
            {{ sourceLabel }}
          </span>
        </span>
        <span
          v-if="item.aiGenerated"
          class="badge badge-soft badge-sm gap-1"
          title="Generated by an AI model"
          data-testid="document-row-ai"
        >
          <Icon
            name="lucide:sparkles"
            size="10"
            aria-hidden="true"
          />
          AI
        </span>
        <span data-testid="document-row-meta">
          {{ metaLabel }}
        </span>
        <UiLocalDate :value="item.createdAt" />
      </div>
    </div>

    <details
      ref="dropdownRef"
      class="
        dropdown dropdown-end relative z-20 open:z-40
        transition-opacity
        sm:opacity-0 sm:group-hover:opacity-100 sm:focus-within:opacity-100
      "
      :class="isFlippedUp ? 'dropdown-top' : 'dropdown-bottom'"
      @toggle="updatePlacement"
    >
      <summary
        data-testid="document-row-actions-trigger"
        class="btn btn-ghost btn-sm sm:btn-xs btn-circle"
        aria-label="Document actions"
      >
        <Icon name="lucide:ellipsis-vertical" size="16" />
      </summary>
      <div
        class="dropdown-content z-50 w-64"
        :class="isFlippedUp ? 'pb-2' : 'pt-2'"
        data-testid="document-row-actions-menu"
      >
        <ul
          tabindex="0"
          class="menu menu-sm bg-base-100 rounded-box shadow-lg w-64 p-1"
        >
          <li>
            <button
              type="button"
              data-testid="document-action-preview"
              @click="onPreview"
            >
              <Icon name="lucide:eye" size="14" />
              Preview
            </button>
          </li>
          <li>
            <a
              :href="downloadUrl"
              download
              data-testid="document-action-download"
              @click="onDownload"
            >
              <Icon name="lucide:download" size="14" />
              Download
            </a>
          </li>
          <li v-if="hasOriginChat">
            <NuxtLink
              :to="`/chats/${item.originChatSlug}`"
              data-testid="document-action-open-chat"
              @click="closeDropdown"
            >
              <Icon name="lucide:message-circle" size="14" />
              Open chat
            </NuxtLink>
          </li>
          <li>
            <button
              type="button"
              data-testid="document-action-rename"
              @click="onRename"
            >
              <Icon name="lucide:pencil" size="14" />
              Rename
            </button>
          </li>
          <li>
            <button
              type="button"
              class="text-error"
              data-testid="document-action-delete"
              @click="onDelete"
            >
              <Icon name="lucide:trash-2" size="14" />
              Delete
            </button>
          </li>
        </ul>
      </div>
    </details>
  </li>
</template>

<script setup lang="ts">
import {
  DOCUMENT_FORMAT_LIBRARY_LABELS,
  DOCUMENT_SOURCE_LIBRARY_LABELS,
} from '#shared/utils/documents'
import type { DocumentLibraryItem } from '#shared/utils/documents'
import { getDocumentMetaLabel } from '~/utils/document-ui'

const UNTITLED_CHAT_LABEL = 'Untitled chat'
const DELETED_CHAT_LABEL = 'Chat deleted'

const props = defineProps<{
  item: DocumentLibraryItem
}>()

const emit = defineEmits<{
  preview: [item: DocumentLibraryItem]
  rename: [item: DocumentLibraryItem]
  delete: [item: DocumentLibraryItem]
}>()

const dropdownRef = useTemplateRef<HTMLDetailsElement>('dropdownRef')
const { isFlippedUp, updatePlacement } = useDropdownPlacement(dropdownRef)
const { onDownloadClick } = useFileDownload()

const isConnectedApp = computed<boolean>(() => {
  return props.item.source === 'mcp'
})

const hasOriginChat = computed<boolean>(() => {
  return !isConnectedApp.value && !!props.item.originChatSlug
})

const sourceLabel = computed<string>(() => {
  return DOCUMENT_SOURCE_LIBRARY_LABELS[props.item.source]
})

const sourceIcon = computed<string>(() => {
  if (isConnectedApp.value) {
    return 'lucide:plug'
  }

  return hasOriginChat.value
    ? 'lucide:message-circle'
    : 'lucide:message-circle-off'
})

const metaLabel = computed<string>(() => {
  return getDocumentMetaLabel(
    props.item.format,
    props.item.stats,
    props.item.size,
  )
})

const downloadUrl = computed<string>(() => {
  return getFileDownloadUrl(props.item.storageKey)
})

onClickOutside(dropdownRef, () => {
  if (dropdownRef.value?.open) {
    closeDropdown()
  }
})

function closeDropdown() {
  if (dropdownRef.value) {
    dropdownRef.value.open = false
    const activeElement = document.activeElement as HTMLElement | null

    activeElement?.blur()
  }
}

function onDownload(event: MouseEvent) {
  onDownloadClick(event, {
    url: downloadUrl.value,
    fileName: props.item.fileName,
  })
  closeDropdown()
}

function onPreview() {
  closeDropdown()
  emit('preview', props.item)
}

function onRename() {
  closeDropdown()
  emit('rename', props.item)
}

function onDelete() {
  closeDropdown()
  emit('delete', props.item)
}
</script>
