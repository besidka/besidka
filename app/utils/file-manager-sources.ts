import type {
  BuiltInFileSourceTab,
  ExtraFileSourceTab,
  FileSourceTab,
} from '~/types/file-manager'

export const fileManagerBuiltInSourceTabs: readonly BuiltInFileSourceTab[] = [
  {
    kind: 'built-in',
    id: 'upload',
    label: 'Uploaded',
    testId: 'files-source-upload',
  },
  {
    kind: 'built-in',
    id: 'assistant',
    label: 'Generated by AI',
    testId: 'files-source-assistant',
    requiresImageInput: true,
  },
  {
    kind: 'built-in',
    id: 'project',
    label: 'Projects',
    testId: 'files-source-project',
  },
]

/**
 * Registry of extra file manager sources (Google Drive, documents). Each
 * entry renders its own component in the file area and gates itself through
 * `isEnabled`, typically a feature flag check.
 */
export function getFileManagerExtraSourceTabs(): ExtraFileSourceTab[] {
  return []
}

export function resolveFileManagerSourceTabs(options: {
  isImageInputSupported: boolean
  extraTabs: readonly ExtraFileSourceTab[]
}): FileSourceTab[] {
  const builtInTabs = fileManagerBuiltInSourceTabs.filter((tab) => {
    return !tab.requiresImageInput || options.isImageInputSupported
  })
  const extraTabs = options.extraTabs.filter((tab) => {
    return tab.isEnabled?.() ?? true
  })

  return [...builtInTabs, ...extraTabs]
}
