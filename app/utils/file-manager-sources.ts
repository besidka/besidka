/**
 * Registry of extra file manager sources (Google Drive, documents). Each
 * entry renders its own component in the file area and gates itself through
 * `isEnabled`, typically a feature flag check.
 */
export function getFileManagerExtraSourceTabs(): ExtraFileSourceTab[] {
  return []
}

export function resolveFileManagerSourceTabs(options: {
  extraTabs: readonly ExtraFileSourceTab[]
}): FileSourceTab[] {
  const builtInTabs = [...fileManagerBuiltInSourceTabs]
  const builtInIds = new Set<string>(fileManagerBuiltInSourceTabs.map((tab) => {
    return tab.id
  }))
  const extraTabs = options.extraTabs.filter((tab) => {
    if (builtInIds.has(tab.id)) {
      return false
    }

    return tab.isEnabled?.() ?? true
  })

  return [...builtInTabs, ...extraTabs]
}
