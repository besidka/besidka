import type { ArtifactKind } from '#shared/utils/artifacts'

export interface ArtifactExportOptions {
  modelId?: string | null
}

export interface ArtifactSourceFile {
  fileName: string
  content: string
  mimeType: string
}

export type StandaloneArtifactKind = Extract<
  ArtifactKind,
  'html' | 'markdown'
>

export const ARTIFACT_AI_MARK = 'AI-generated by Besidka'

const AI_GENERATED_META = '<meta name="ai-generated" content="true">'
const EXPORT_CONTENT_SECURITY_POLICY = [
  'default-src \'none\'',
  'script-src \'unsafe-inline\'',
  'style-src \'unsafe-inline\'',
  'img-src data: blob:',
  'font-src data:',
  'media-src data: blob:',
].join('; ')
const EXPORT_CSP_META = '<meta http-equiv="Content-Security-Policy" '
  + `content="${EXPORT_CONTENT_SECURITY_POLICY}">`
const EXPORT_HEAD_METAS = `${EXPORT_CSP_META}\n${AI_GENERATED_META}`
const FILE_NAME_MAX_LENGTH = 80
const FALLBACK_FILE_NAME = 'artifact'

const FILE_EXTENSIONS: Record<ArtifactKind, string> = {
  html: 'html',
  react: 'jsx',
  svg: 'svg',
  mermaid: 'mmd',
  markdown: 'md',
}

const MIME_TYPES: Record<ArtifactKind, string> = {
  html: 'text/html',
  react: 'text/javascript',
  svg: 'image/svg+xml',
  mermaid: 'text/plain',
  markdown: 'text/markdown',
}

const STANDALONE_KINDS = new Set<ArtifactKind>(['markdown'])

const DOCTYPE_PATTERN = /^\s*<!doctype[^>]*>/i
const HEAD_OPEN_PATTERN = /<head(?:\s[^>]*)?>/i
const HTML_OPEN_PATTERN = /<html(?:\s[^>]*)?>/i
const XML_DECLARATION_PATTERN = /^\s*<\?xml[^>]*\?>/i
const UNSAFE_FILE_NAME_CHARACTERS = /[\\/:*?"<>|\p{Cc}]+/gu
const FORMAT_CHARACTERS = /\p{Cf}/gu
const WHITESPACE_RUN = /\s+/g
const EDGE_SEPARATORS = /^[-.\s]+|[-.\s]+$/g
const MODEL_ID_UNSAFE_CHARACTERS = /[^\w.:/@+-]+/g

export function artifactFileName(title: string, kind: ArtifactKind): string {
  const base = title
    .normalize('NFC')
    .replace(FORMAT_CHARACTERS, '')
    .replace(UNSAFE_FILE_NAME_CHARACTERS, ' ')
    .replace(WHITESPACE_RUN, '-')
    .replace(EDGE_SEPARATORS, '')
    .slice(0, FILE_NAME_MAX_LENGTH)
    .replace(EDGE_SEPARATORS, '')

  return `${base || FALLBACK_FILE_NAME}.${FILE_EXTENSIONS[kind]}`
}

export function canExportStandaloneHtml(
  kind: ArtifactKind,
): kind is StandaloneArtifactKind {
  return STANDALONE_KINDS.has(kind)
}

function escapeHtml(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
}

function getAiMarkComment(options: ArtifactExportOptions): string {
  const modelId = options.modelId
    ?.replace(MODEL_ID_UNSAFE_CHARACTERS, '')
    .replace(/-{2,}/g, '-')
    .slice(0, 120)

  return modelId
    ? `<!-- ${ARTIFACT_AI_MARK} (model: ${modelId}) -->`
    : `<!-- ${ARTIFACT_AI_MARK} -->`
}

function insertAfterMatch(
  source: string,
  pattern: RegExp,
  insertion: string,
): string | null {
  const match = pattern.exec(source)

  if (!match) {
    return null
  }

  const end = match.index + match[0].length

  return `${source.slice(0, end)}${insertion}${source.slice(end)}`
}

function withAiMarkComment(
  document: string,
  options: ArtifactExportOptions,
): string {
  const comment = getAiMarkComment(options)

  return insertAfterMatch(document, DOCTYPE_PATTERN, `\n${comment}`)
    ?? `${comment}\n${document}`
}

function wrapInDocument(title: string, body: string): string {
  return [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    EXPORT_CSP_META,
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    AI_GENERATED_META,
    `<title>${escapeHtml(title)}</title>`,
    '</head>',
    '<body>',
    body,
    '</body>',
    '</html>',
    '',
  ].join('\n')
}

function buildHtmlDocument(content: string, title: string): string {
  const withHeadMeta = insertAfterMatch(
    content,
    HEAD_OPEN_PATTERN,
    `\n${EXPORT_HEAD_METAS}`,
  )

  if (withHeadMeta !== null) {
    return withHeadMeta
  }

  const withHead = insertAfterMatch(
    content,
    HTML_OPEN_PATTERN,
    `\n<head>${EXPORT_HEAD_METAS}</head>`,
  )

  return withHead ?? wrapInDocument(title, content)
}

function buildMarkdownDocument(content: string, title: string): string {
  const style = 'white-space:pre-wrap;word-break:break-word;'
    + 'font:15px/1.6 ui-monospace,SFMono-Regular,Menlo,monospace;'
    + 'max-width:72ch;margin:2rem auto;padding:0 1rem'

  return wrapInDocument(
    title,
    `<pre style="${style}">${escapeHtml(content)}</pre>`,
  )
}

/**
 * A self-contained HTML file for an artifact that references no third-party
 * host. The sandbox runtime is not part of the export, so only kinds that
 * need no runtime library are supported: HTML as written, and Markdown as
 * readable source. React and Mermaid artifacts are exported as source only.
 * A Content-Security-Policy meta right after `<head>` blocks every network
 * load, so an exported file opened locally cannot reach any host. Every
 * export carries the AI-generated meta tag and comment (AI Act Art. 50(2),
 * pre-check A-12 row 4); the model id appears only when known.
 */
export function buildStandaloneArtifactHtml(
  kind: StandaloneArtifactKind,
  content: string,
  options: ArtifactExportOptions & { title?: string } = {},
): string {
  const title = options.title || FALLBACK_FILE_NAME
  const document = kind === 'html'
    ? buildHtmlDocument(content, title)
    : buildMarkdownDocument(content, title)

  return withAiMarkComment(document, options)
}

function markSvgSource(content: string): string {
  const comment = `<!-- ${ARTIFACT_AI_MARK} -->`

  return insertAfterMatch(content, XML_DECLARATION_PATTERN, `\n${comment}`)
    ?? `${comment}\n${content}`
}

/**
 * The file behind "Download source". HTML gets the same marks as the
 * standalone export, Markdown and SVG get a one-line comment, JSX and
 * Mermaid source stay unmarked (source code, AI Act guidelines para 68).
 */
export function buildArtifactSourceFile(
  kind: ArtifactKind,
  content: string,
  options: ArtifactExportOptions & { title?: string } = {},
): ArtifactSourceFile {
  const fileName = artifactFileName(options.title ?? '', kind)
  const mimeType = MIME_TYPES[kind]

  if (kind === 'html') {
    return {
      fileName,
      mimeType,
      content: buildStandaloneArtifactHtml('html', content, options),
    }
  }

  if (kind === 'markdown') {
    return {
      fileName,
      mimeType,
      content: `<!-- ${ARTIFACT_AI_MARK} -->\n${content}`,
    }
  }

  if (kind === 'svg') {
    return { fileName, mimeType, content: markSvgSource(content) }
  }

  return { fileName, mimeType, content }
}

export function buildStandaloneArtifactFile(
  kind: StandaloneArtifactKind,
  content: string,
  options: ArtifactExportOptions & { title?: string } = {},
): ArtifactSourceFile {
  const baseName = artifactFileName(options.title ?? '', kind)
    .replace(/\.[^.]+$/, '')

  return {
    fileName: `${baseName}.html`,
    mimeType: 'text/html',
    content: buildStandaloneArtifactHtml(kind, content, options),
  }
}

export function downloadArtifactFile(
  file: ArtifactSourceFile,
): Promise<boolean> {
  return useFileDownload().downloadBlob({
    key: `artifact:${file.fileName}:${hashText(file.content)}`,
    fileName: file.fileName,
    build: () => {
      return new Blob([file.content], {
        type: `${file.mimeType};charset=utf-8`,
      })
    },
  })
}
