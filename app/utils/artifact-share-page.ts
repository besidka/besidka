export type ArtifactSharePageState
  = | 'loading'
    | 'ready'
    | 'not-found'
    | 'taken-down'
    | 'error'

export type ArtifactSharePageFetchStatus
  = 'idle' | 'pending' | 'success' | 'error'

export interface ArtifactSharePageStateInput {
  status: ArtifactSharePageFetchStatus
  hasData: boolean
  error: unknown
}

export const ARTIFACT_SHARE_BANNER_TEXT
  = 'AI-generated by a Besidka user, not reviewed by Besidka.'

export const ARTIFACT_SHARE_BANNER_WARNING
  = 'Never enter passwords or payment details here.'

export const ARTIFACT_SHARE_TAKEN_DOWN_CODE = 'artifact_taken_down'

export const ARTIFACT_SHARE_STATE_COPY: Record<
  ArtifactSharePageState,
  { title: string, description: string }
> = {
  'loading': { title: 'Loading', description: '' },
  'ready': { title: '', description: '' },
  'not-found': {
    title: 'This link is not available',
    description: 'It may have expired, or its owner turned it off.',
  },
  'taken-down': {
    title: 'This artifact was removed after a report',
    description: 'Besidka removed it because it broke the rules for shared '
      + 'content.',
  },
  'error': {
    title: 'The artifact did not load',
    description: 'Something went wrong. Try again in a moment.',
  },
}

function readErrorStatus(error: unknown): number {
  const { statusCode, status } = (error ?? {}) as {
    statusCode?: unknown
    status?: unknown
  }
  const value = [statusCode, status].find((candidate) => {
    return typeof candidate === 'number'
  })

  return typeof value === 'number' ? value : 0
}

/**
 * True for the 410 a takedown answers. A 410 for a missing stored version
 * carries no `takenDown` flag and is shown as a load error instead.
 */
export function isArtifactShareTakenDownError(error: unknown): boolean {
  if (readErrorStatus(error) !== 410) {
    return false
  }

  const body = (error as { data?: unknown } | null)?.data as {
    code?: unknown
    takenDown?: unknown
    data?: { takenDown?: unknown, code?: unknown }
  } | undefined

  return body?.data?.takenDown === true
    || body?.takenDown === true
    || body?.code === ARTIFACT_SHARE_TAKEN_DOWN_CODE
    || body?.data?.code === ARTIFACT_SHARE_TAKEN_DOWN_CODE
}

export function resolveArtifactSharePageState(
  input: ArtifactSharePageStateInput,
): ArtifactSharePageState {
  if (input.error) {
    if (readErrorStatus(input.error) === 404) {
      return 'not-found'
    }

    return isArtifactShareTakenDownError(input.error)
      ? 'taken-down'
      : 'error'
  }

  if (input.hasData) {
    return 'ready'
  }

  return input.status === 'success' ? 'error' : 'loading'
}
