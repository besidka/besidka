describe('encodeQrCode', () => {
  it('encodes a short byte-mode string at level M to version 1', () => {
    const matrix = encodeQrCode('hello', 'M')

    expect(matrix).toEqual(rowsToMatrix(helloVersion1LevelMRows))
  })

  it('encodes the same short string at level L to a different matrix', () => {
    const matrix = encodeQrCode('hello', 'L')

    expect(matrix).toEqual(rowsToMatrix(helloVersion1LevelLRows))
  })

  it('defaults to error correction level M when unspecified', () => {
    const matrix = encodeQrCode('hello')

    expect(matrix).toEqual(rowsToMatrix(helloVersion1LevelMRows))
  })

  it('encodes a realistic otpauth:// URI to version 7 at level M', () => {
    const otpauthUri = 'otpauth://totp/Besidka:user@example.com?secret='
      + 'JBSWY3DPEHPK3PXP&issuer=Besidka&algorithm=SHA1&digits=6&period=30'

    const matrix = encodeQrCode(otpauthUri, 'M')

    expect(matrix).toEqual(rowsToMatrix(otpauthVersion7LevelMRows))
  })

  it(
    'encodes a long byte-mode string into version 10 at level M '
    + '(16-bit character count indicator, multi-group block interleave)',
    () => {
      const matrix = encodeQrCode('a'.repeat(200), 'M')

      expect(matrix).toEqual(rowsToMatrix(longVersion10LevelMRows))
    },
  )

  it('throws when the input is too long for version 10 at level M', () => {
    const tooLong = 'a'.repeat(214)

    expect(() => encodeQrCode(tooLong, 'M')).toThrow()
  })

  it('produces a square matrix sized for the selected version', () => {
    const version1Matrix = encodeQrCode('hi', 'M')
    const version7Matrix = encodeQrCode('a'.repeat(110), 'M')

    expect(version1Matrix.length).toBe(21)
    expect(version1Matrix.every(row => row.length === 21)).toBe(true)
    expect(version7Matrix.length).toBe(45)
    expect(version7Matrix.every(row => row.length === 45)).toBe(true)
  })
})

describe('qrMatrixToSvg', () => {
  it('renders one <rect> per dark module inside the dark-fill group', () => {
    const matrix = encodeQrCode('hello', 'M')
    const svg = qrMatrixToSvg(matrix)

    const darkModuleCount = matrix
      .flat()
      .filter(module => module)
      .length

    const darkGroupMatch = svg.match(
      /<g fill="#000">([\s\S]*)<\/g>/,
    )

    expect(svg).toContain('<svg')
    expect(darkGroupMatch).not.toBeNull()

    const rectCount = darkGroupMatch
      ? (darkGroupMatch[1].match(/<rect/g)?.length ?? 0)
      : 0

    expect(rectCount).toBe(darkModuleCount)
  })

  it('sizes the viewBox to the matrix plus the quiet-zone margin', () => {
    const matrix = encodeQrCode('hello', 'M')
    const svg = qrMatrixToSvg(matrix)

    expect(svg).toContain(
      `viewBox="0 0 ${21 + 4 * 2} ${21 + 4 * 2}"`,
    )
  })

  it('respects a custom margin option', () => {
    const matrix = encodeQrCode('hello', 'M')
    const svg = qrMatrixToSvg(matrix, { margin: 0 })

    expect(svg).toContain('viewBox="0 0 21 21"')
  })
})
