import { describe, expect, it } from 'vitest'
import {
  ARTIFACT_AI_MARK,
  artifactFileName,
  buildArtifactSourceFile,
  buildStandaloneArtifactFile,
  buildStandaloneArtifactHtml,
  canExportStandaloneHtml,
} from '../../../app/utils/artifact-export'

const AI_META = '<meta name="ai-generated" content="true">'
const CSP_META = '<meta http-equiv="Content-Security-Policy" content="'
  + 'default-src \'none\'; script-src \'unsafe-inline\'; '
  + 'style-src \'unsafe-inline\'; img-src data: blob:; font-src data:; '
  + 'media-src data: blob:">'
const THIRD_PARTY_HOST = /https?:\/\/(?!localhost)/

describe('artifactFileName', () => {
  it('uses the extension of each kind', () => {
    expect(artifactFileName('Landing page', 'html')).toBe('Landing-page.html')
    expect(artifactFileName('Counter', 'react')).toBe('Counter.jsx')
    expect(artifactFileName('Logo', 'svg')).toBe('Logo.svg')
    expect(artifactFileName('Flow', 'mermaid')).toBe('Flow.mmd')
    expect(artifactFileName('Notes', 'markdown')).toBe('Notes.md')
  })

  it('strips characters that are unsafe in file names', () => {
    expect(artifactFileName('a/b\\c:d*e?"f<g>h|i', 'html'))
      .toBe('a-b-c-d-e-f-g-h-i.html')
    expect(artifactFileName('  ..Report.. ', 'markdown')).toBe('Report.md')
  })

  it('strips bidi and other format controls', () => {
    expect(artifactFileName('invoice\u202Egnp.exe', 'html'))
      .toBe('invoicegnp.exe.html')
    expect(artifactFileName('a\u200Bb\u2066c\u2069\uFEFF', 'svg'))
      .toBe('abc.svg')
  })

  it('falls back to a generic name and caps the length', () => {
    expect(artifactFileName('', 'svg')).toBe('artifact.svg')
    expect(artifactFileName('///', 'svg')).toBe('artifact.svg')
    expect(artifactFileName('x'.repeat(200), 'html')).toBe(
      `${'x'.repeat(80)}.html`,
    )
  })

  it('keeps non-latin titles', () => {
    expect(artifactFileName('Бесідка план', 'markdown'))
      .toBe('Бесідка-план.md')
  })
})

describe('buildStandaloneArtifactHtml', () => {
  it('adds the meta tag to an existing head and the comment after the '
    + 'doctype', () => {
    const html = buildStandaloneArtifactHtml(
      'html',
      '<!doctype html><html><head><title>A</title></head><body></body></html>',
    )

    expect(html.startsWith('<!doctype html>\n<!-- AI-generated by Besidka -->'))
      .toBe(true)
    expect(html).toContain(`<head>\n${CSP_META}\n${AI_META}<title>A</title>`)
  })

  it('creates a head when the document has none', () => {
    const html = buildStandaloneArtifactHtml(
      'html',
      '<html lang="en"><body>Hi</body></html>',
    )

    expect(html).toContain(
      `<html lang="en">\n<head>${CSP_META}\n${AI_META}</head>`,
    )
    expect(html.startsWith(`<!-- ${ARTIFACT_AI_MARK} -->`)).toBe(true)
  })

  it('wraps an HTML fragment in a full document', () => {
    const html = buildStandaloneArtifactHtml('html', '<p>Hi</p>', {
      title: 'Tom & <Jerry>',
    })

    expect(html).toContain('<!doctype html>')
    expect(html).toContain(`<head>\n${CSP_META}\n<meta charset="utf-8">`)
    expect(html).toContain(AI_META)
    expect(html).toContain('<title>Tom &amp; &lt;Jerry&gt;</title>')
    expect(html).toContain('<p>Hi</p>')
  })

  it('names the model only when it is known', () => {
    const withModel = buildStandaloneArtifactHtml('html', '<p>x</p>', {
      modelId: 'anthropic/claude-opus-4.5',
    })
    const injected = buildStandaloneArtifactHtml('html', '<p>x</p>', {
      modelId: 'x --> <script>alert(1)</script>',
    })
    const withoutModel = buildStandaloneArtifactHtml('html', '<p>x</p>')

    expect(withModel).toContain(
      `<!-- ${ARTIFACT_AI_MARK} (model: anthropic/claude-opus-4.5) -->`,
    )
    expect(injected.match(/-->/g)).toHaveLength(1)
    expect(injected).not.toContain('<script>')
    expect(withoutModel).toContain(`<!-- ${ARTIFACT_AI_MARK} -->`)
    expect(withoutModel).not.toContain('model:')
  })

  it('renders markdown as escaped readable source', () => {
    const html = buildStandaloneArtifactHtml(
      'markdown',
      '# Title\n\n<script>alert(1)</script>',
      { title: 'Notes' },
    )

    expect(html).toContain('# Title')
    expect(html).toContain('&lt;script&gt;alert(1)&lt;/script&gt;')
    expect(html).not.toContain('<script>alert(1)</script>')
    expect(html).toContain(AI_META)
  })

  it('references no third-party host', () => {
    const html = buildStandaloneArtifactHtml('markdown', '# Hi')

    expect(html).not.toMatch(THIRD_PARTY_HOST)
    expect(html).not.toContain('esm.sh')
    expect(html).toContain(CSP_META)
  })

  it('blocks network loads of exported html with a restrictive policy',
    () => {
      const html = buildStandaloneArtifactHtml(
        'html',
        '<html><head><script src="https://cdn.example/x.js"></script>'
        + '</head></html>',
      )

      expect(html.indexOf(CSP_META)).toBeLessThan(html.indexOf('<script'))
      expect(html.match(/Content-Security-Policy/g)).toHaveLength(1)
    })
})

describe('canExportStandaloneHtml', () => {
  it('offers the HTML export only for kinds that need no runtime', () => {
    expect(canExportStandaloneHtml('markdown')).toBe(true)
    expect(canExportStandaloneHtml('react')).toBe(false)
    expect(canExportStandaloneHtml('mermaid')).toBe(false)
    expect(canExportStandaloneHtml('svg')).toBe(false)
    expect(canExportStandaloneHtml('html')).toBe(false)
  })
})

describe('buildArtifactSourceFile', () => {
  it('marks markdown with a one-line HTML comment', () => {
    const file = buildArtifactSourceFile('markdown', '# Hi', { title: 'Hi' })

    expect(file.fileName).toBe('Hi.md')
    expect(file.content).toBe(`<!-- ${ARTIFACT_AI_MARK} -->\n# Hi`)
  })

  it('marks svg after the XML declaration', () => {
    const file = buildArtifactSourceFile(
      'svg',
      '<?xml version="1.0"?><svg></svg>',
      { title: 'Logo' },
    )

    expect(file.content).toBe(
      `<?xml version="1.0"?>\n<!-- ${ARTIFACT_AI_MARK} --><svg></svg>`,
    )
    expect(file.mimeType).toBe('image/svg+xml')
  })

  it('marks svg without a declaration at the start', () => {
    const file = buildArtifactSourceFile('svg', '<svg></svg>')

    expect(file.content).toBe(`<!-- ${ARTIFACT_AI_MARK} -->\n<svg></svg>`)
  })

  it('leaves jsx and mermaid source unmarked', () => {
    const react = buildArtifactSourceFile('react', 'export default 1', {
      title: 'App',
    })
    const mermaid = buildArtifactSourceFile('mermaid', 'graph TD; A-->B', {
      title: 'Flow',
    })

    expect(react).toMatchObject({
      fileName: 'App.jsx',
      content: 'export default 1',
    })
    expect(mermaid).toMatchObject({
      fileName: 'Flow.mmd',
      content: 'graph TD; A-->B',
    })
  })

  it('downloads html source with the standalone marks', () => {
    const file = buildArtifactSourceFile('html', '<p>x</p>', { title: 'Page' })

    expect(file.fileName).toBe('Page.html')
    expect(file.content).toContain(AI_META)
    expect(file.content).toContain(`<!-- ${ARTIFACT_AI_MARK} -->`)
  })
})

describe('buildStandaloneArtifactFile', () => {
  it('names the markdown export as an html file', () => {
    const file = buildStandaloneArtifactFile('markdown', '# Hi', {
      title: 'Notes',
    })

    expect(file.fileName).toBe('Notes.html')
    expect(file.mimeType).toBe('text/html')
    expect(file.content).toContain(AI_META)
  })
})
