import { defineComponent } from 'vue'
import { describe, expect, it } from 'vitest'
import type { ExtraFileSourceTab } from '../../../app/types/file-manager'
import {
  GENERATED_FILES_TAB_LABEL,
  fileManagerBuiltInSourceTabs,
  fileManagerKindFilterOptions,
  getFileManagerExtraSourceTabs,
  isAiGeneratedFile,
  isConnectedAppFile,
  resolveFileManagerSourceTabs,
} from '../../../app/utils/file-manager-sources'

const FakeSource = defineComponent({ name: 'FakeSource', render: () => null })

function createExtraTab(
  overrides: Partial<ExtraFileSourceTab> = {},
): ExtraFileSourceTab {
  return {
    kind: 'extra',
    id: 'drive',
    label: 'Google Drive',
    testId: 'files-source-drive',
    component: FakeSource,
    ...overrides,
  }
}

describe('utils/file-manager-sources', () => {
  it('keeps the built-in tab ids, labels and test ids', () => {
    expect(fileManagerBuiltInSourceTabs.map((tab) => {
      return [tab.id, tab.label, tab.testId]
    })).toEqual([
      ['upload', 'Uploaded', 'files-source-upload'],
      ['assistant', 'Generated by AI', 'files-source-assistant'],
      ['project', 'Projects', 'files-source-project'],
    ])
  })

  it('registers no extra sources yet', () => {
    expect(getFileManagerExtraSourceTabs()).toEqual([])
  })

  it('keeps the generated tab for every model', () => {
    const tabs = resolveFileManagerSourceTabs({ extraTabs: [] })

    expect(tabs.map(tab => tab.id)).toEqual([
      'upload',
      'assistant',
      'project',
    ])
  })

  it('keeps the generated tab label in one constant', () => {
    const generatedTab = fileManagerBuiltInSourceTabs.find((tab) => {
      return tab.id === 'assistant'
    })

    expect(GENERATED_FILES_TAB_LABEL).toBe('Generated by AI')
    expect(generatedTab?.label).toBe(GENERATED_FILES_TAB_LABEL)
  })

  it('lists the kind filter options in order', () => {
    expect(fileManagerKindFilterOptions.map((option) => {
      return [option.id, option.label, option.testId]
    })).toEqual([
      ['all', 'All', 'files-kind-all'],
      ['image', 'Images', 'files-kind-image'],
      ['document', 'Documents', 'files-kind-document'],
    ])
  })

  it('appends enabled extra sources and hides disabled ones', () => {
    const tabs = resolveFileManagerSourceTabs({
      extraTabs: [
        createExtraTab(),
        createExtraTab({
          id: 'documents',
          testId: 'files-source-documents',
          isEnabled: () => false,
        }),
        createExtraTab({
          id: 'flagged',
          testId: 'files-source-flagged',
          isEnabled: () => true,
        }),
      ],
    })

    expect(tabs.map(tab => tab.id)).toEqual([
      'upload',
      'assistant',
      'project',
      'drive',
      'flagged',
    ])
  })

  it('drops an extra source whose id collides with a built-in tab', () => {
    const tabs = resolveFileManagerSourceTabs({
      extraTabs: [createExtraTab({ id: 'upload' })],
    })

    expect(tabs.map(tab => tab.id)).toEqual(['upload', 'assistant', 'project'])
    expect(tabs.every(tab => tab.kind === 'built-in')).toBe(true)
  })
})

describe('isConnectedAppFile', () => {
  const base = {
    id: 'file-1',
    storageKey: 'file-1.pdf',
    name: 'Report.pdf',
    size: 1,
    type: 'application/pdf',
    source: 'assistant' as const,
    expiresAt: null,
    createdAt: new Date(),
    originModel: null,
    generationCost: null,
  }

  it('is true only for a document file flagged as not AI', () => {
    const connectedApp = {
      ...base,
      documentId: 'doc-1',
      documentAiGenerated: false,
    }

    expect(isConnectedAppFile(connectedApp)).toBe(true)
    expect(isAiGeneratedFile(connectedApp)).toBe(false)
  })

  it.each([true, null, undefined])(
    'leaves a file with an AI flag of %s labelled as AI',
    (documentAiGenerated) => {
      const file = { ...base, documentId: 'doc-1', documentAiGenerated }

      expect(isConnectedAppFile(file)).toBe(false)
      expect(isAiGeneratedFile(file)).toBe(true)
    },
  )

  it('never marks an uploaded file', () => {
    const upload = {
      ...base,
      source: 'upload' as const,
      documentId: 'doc-1',
      documentAiGenerated: false,
    }

    expect(isConnectedAppFile(upload)).toBe(false)
    expect(isAiGeneratedFile(upload)).toBe(false)
  })
})
